function enhanceBasicCodingUnit(unit) {
  return {
    ...unit,
    example: unit.example
      ? {
          ...unit.example,
          sequence: (unit.example.sequence || []).map((item, index) => ({
            ...item,
            iosVisualKey: iosVisualKey(index),
          })),
        }
      : unit.example,
    activity: {
      ...unit.activity,
      tasks: getBasicCodingTasks(unit.id, unit.activity),
    },
    questions: getBasicCodingQuestions(unit.id, unit.questions),
  };
}

function enhanceCreativeCodingUnit(unit) {
  const questions = getCreativeCodingQuestions(unit.id);
  const tasks = getCreativeCodingTasks(unit.id);
  return {
    ...unit,
    material: (unit.material || []).slice(0, 2),
    example: unit.example
      ? {
          ...unit.example,
          sequence: (unit.example.sequence || []).map((item, index) => ({
            ...item,
            iosVisualKey: iosCreativeVisualKey(index),
          })),
        }
      : unit.example,
    activity: tasks ? { ...unit.activity, tasks } : unit.activity,
    questions: questions || unit.questions,
    ...(unit.id === 'creative-g56-proyek-website-profilku'
      || unit.id === 'creative-g34-proyek-pameran-karyaku'
      ? {
          safetyReminder: {
            id: 'Jangan bagikan alamat rumah, nomor telepon, atau nama sekolah secara online.',
            en: 'Do not share your home address, phone number, or school name online.',
          },
        }
      : {}),
  };
}

